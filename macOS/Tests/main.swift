import Foundation

func require(_ condition: @autoclosure () -> Bool, _ description: String) {
    if !condition() { fatalError(description) }
}

// CRC-16/CCITT-FALSE standard check string; golden packets independently
// calculated with Python's binascii.crc_hqx, shared with the C decoder tests.
require(RGBProtocol.crc16(Array("123456789".utf8)) == 0x29b1, "CRC standard vector")
require(RGBProtocol.packet(hue: 0, saturation: 255, value: 255) ==
        [0x4b,0x52,0x47,0x42,1,1,0,255,255,0xe3,0xc0], "red golden frame")
require(RGBProtocol.packet(hue: 85, saturation: 192, value: 128) ==
        [0x4b,0x52,0x47,0x42,1,1,85,192,128,0xcc,0x2d], "color golden frame")
require(RGBProtocol.packet(hue: 255, saturation: 255, value: 255, off: true) ==
        [0x4b,0x52,0x47,0x42,1,2,0,0,0,0x65,0x13], "off resets payload")

for h in UInt16(0)...255 {
    let frame = RGBProtocol.packet(hue: UInt8(h), saturation: 127, value: 192)
    let masks = RGBProtocol.masks(for: frame)
    require(masks.count == 45 && masks[0] == 0, "baseline and symbol count")
    var decoded: [UInt8] = []
    var byte: UInt8 = 0
    for (index, mask) in masks.dropFirst().enumerated() {
        require(mask <= 7, "only three LED bits")
        require((mask & 4) == (index % 2 == 0 ? 4 : 0), "clock toggles every symbol")
        byte = (byte << 2) | (mask & 3)
        if index % 4 == 3 { decoded.append(byte); byte = 0 }
    }
    require(decoded == frame, "MSB-first bit ordering")
}
print("Swift protocol: CRC, 3 golden frames and 256 symbol round trips passed. No HID reports sent.")

let v2Vectors: [(Int, UInt8, UInt8, UInt8, UInt8, [UInt8])] = [
    (1, 0, 255, 255, 127, [0x4b,0x52,0x47,0x42,2,3,1,0,255,255,127,0xa2,0x1a]),
    (20, 85, 192, 128, 200, [0x4b,0x52,0x47,0x42,2,3,20,85,192,128,200,0x6a,0xa6]),
    (0, 255, 255, 255, 255, [0x4b,0x52,0x47,0x42,2,3,0,0,0,0,0,0x4b,0xaf]),
    (22, 255, 255, 255, 255, [0x4b,0x52,0x47,0x42,2,3,22,255,255,255,255,0x1b,0xbf])
]
for (mode,h,s,v,speed,expected) in v2Vectors {
    let packet = try RGBProtocol.statePacket(effect:mode,hue:h,saturation:s,value:v,speed:speed)
    require(packet == expected, "v2 independent golden vector")
    let masks = RGBProtocol.masks(for:packet)
    require(masks.count == 53 && RGBProtocol.validMasks(masks), "v2 transport accepts valid frame")
    for i in 1..<masks.count {
        for bit: UInt8 in [1,2,4] {
            var corrupt = masks; corrupt[i] ^= bit
            require(!RGBProtocol.validMasks(corrupt), "corrupt v2 symbol rejected")
        }
        require(!RGBProtocol.validMasks(Array(masks.prefix(i))), "truncated v2 frame rejected")
    }
}
for mode in 0...22 {
    for speed in 0...255 {
        let packet = try RGBProtocol.statePacket(effect:mode,hue:UInt8(speed),saturation:192,value:128,speed:UInt8(speed))
        require(RGBProtocol.validMasks(RGBProtocol.masks(for:packet)), "all modes/speeds transport acceptance")
    }
}
for mode in [-1,23,24,255] {
    require((try? RGBProtocol.statePacket(effect:mode,hue:0,saturation:0,value:0,speed:0)) == nil, "unsupported effect rejected")
}
require(RGBProtocol.validMasks(RGBProtocol.masks(for:RGBProtocol.packet(hue:0,saturation:255,value:255))), "legacy frame accepted")
print("Swift v2: 4 golden frames, 5888 mode/speed cases, corrupted/truncated frames and unsupported effects passed. No HID reports sent.")

// Independent Python binascii.crc_hqx vectors, not generated by this encoder.
let v3Vectors: [(Bool, Int, [UInt8])] = [
    (false, 2, [0x4b,0x52,0x47,0x42,3,3,2,85,255,239,127,0x3e,0xa4]),
    (true, 2, [0x4b,0x52,0x47,0x42,3,4,2,85,255,239,127,0xf6,0xe5]),
    (true, 0, [0x4b,0x52,0x47,0x42,3,4,0,0,0,0,0,0x3b,0x8f])
]
for (save, mode, expected) in v3Vectors {
    let packet = try RGBProtocol.directStatePacket(effect: mode, hue: 85, saturation: 255, value: 239, speed: 127, save: save)
    require(packet == expected, "v3 independent golden vector")
    let masks = RGBProtocol.masks(for: packet)
    require(RGBProtocol.validMasks(masks), "v3 transport accepts valid frame")
    for i in 1..<masks.count {
        for bit: UInt8 in [1,2,4] {
            var corrupt = masks; corrupt[i] ^= bit
            require(!RGBProtocol.validMasks(corrupt), "corrupt v3 symbol rejected")
        }
        require(!RGBProtocol.validMasks(Array(masks.prefix(i))), "truncated v3 frame rejected")
    }
}
for save in [false, true] {
    for mode in 0...22 {
        for speed in 0...255 {
            let packet = try RGBProtocol.directStatePacket(effect: mode, hue: UInt8(speed), saturation: 192, value: 128, speed: UInt8(speed), save: save)
            require(RGBProtocol.validMasks(RGBProtocol.masks(for: packet)), "v3 all effects and speeds")
        }
    }
    for invalid in [-1,23,24,255] {
        require((try? RGBProtocol.directStatePacket(effect: invalid, hue: 0, saturation: 0, value: 0, speed: 0, save: save)) == nil, "v3 rejects custom effect")
    }
}
for version: UInt8 in [1,2,3,4,255] {
    for command: UInt8 in [0,1,2,3,4,5,255] {
        var packet: [UInt8] = [0x4b,0x52,0x47,0x42,version,command,1,85,255,239,127]
        let crc = RGBProtocol.crc16(packet); packet += [UInt8(crc >> 8), UInt8(crc & 255)]
        let expected = (version == 2 && command == 3) || (version == 3 && [3,4].contains(command))
        require(RGBProtocol.validMasks(RGBProtocol.masks(for: packet)) == expected, "Only supported version/command pairs can reach HID")
    }
}
print("Swift v3: preview/save golden vectors, 11776 effect/speed cases, corruption/truncation and command boundaries passed. No HID reports sent.")
